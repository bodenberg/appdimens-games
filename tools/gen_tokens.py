#!/usr/bin/env python3
"""Generates the family token API of the non-Kotlin bindings, used the AppDimens way (token applied to a value):

  C#      64f.Sdp()  64.ASdp()  18f.Ssp()  64f.HdpLw()     dotnet/AppDimens.Games/Tokens.cs (+ Unity copy via sync)
  GDScript AppDimens.sdp(64)  AppDimens.asdpa(64)          engines/godot/addons/appdimens/appdimens.gd (block)
  C++     appdimens::sdp(64)  64_sdp  appdimens::asdp(64)  native/include/appdimens/tokens.hpp

Names follow each family: C# like AppDimens.Net (Sdp, ASdp, DGSdp, LOGSdp, SdpPh, Sdpa), GDScript and C++ like
Kotlin/Web (sdp, asdp, dgsdp, logsdp, sdpPh, sdpa). `--check` fails when an output is stale.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PREFIX = ["", "a", "p", "pw", "f", "i", "log", "dg", "pr", "ft", "fl", "d"]
AXES = [("s", 0), ("h", 1), ("w", 2)]
KINDS = [("dp", 0), ("sp", 1), ("em", 2)]
FLAGS = [("", 0), ("a", 1), ("i", 2), ("ia", 3)]
INV = [("sdpPh", 3), ("sdpLh", 4), ("sdpPw", 5), ("sdpLw", 6), ("hdpLw", 7), ("hdpPw", 8), ("wdpLh", 9), ("wdpPh", 10)]

tokens = []  # (name, strategy, slot, kind, px)
for si, p in enumerate(PREFIX):
    for ax, v in AXES:
        for k, kind in KINDS:
            for fl, f in FLAGS:
                tokens.append((p + ax + k + fl, si, v * 4 + f, kind, False))
        for fl, f in FLAGS:
            tokens.append((p + ax + "dpPx" + fl, si, v * 4 + f, 0, True))
for si in (0, 1):
    for name, v in INV:
        for fl, f in FLAGS:
            tokens.append((PREFIX[si] + name + fl, si, v * 4 + f, 0, False))
low = [t[0].lower() for t in tokens]
assert len(set(low)) == len(low), "case-insensitive clash"

def cs_name(t):
    for p in sorted(PREFIX, key=len, reverse=True):
        if p and t.startswith(p) and t[len(p)] in "shw":
            return p.upper() + t[len(p)].upper() + t[len(p) + 1:]
    return t[0].upper() + t[1:]

cs_names = [cs_name(t[0]) for t in tokens]
assert len(set(cs_names)) == len(cs_names)

# ── C# ──
cs = ["// Generated by tools/gen_tokens.py — do not edit by hand.",
      "// Family token API, the AppDimens.Net way: 64f.Sdp(), 64.ASdp(), 18f.Ssp(), 64f.HdpLw() — values from Live.Current",
      "// (REFERENCE mode: px at the reference resolution → px now).",
      "namespace AppDimens.Games",
      "{",
      "    public static class Tokens",
      "    {",
      "        private static float V(int s, int slot, int kind, bool px, float v)",
      "        {",
      "            var m = Live.Current;",
      "            if (kind == 1) return px ? m.SpPx((Strategy)s, slot, v) : m.Sp((Strategy)s, slot, v);",
      "            return px ? m.Px((Strategy)s, slot, v) : m.Dp((Strategy)s, slot, v);",
      "        }"]
for (n, s, slot, kind, px), c in zip(tokens, cs_names):
    args = "%d, %d, %d, %s" % (s, slot, kind, "true" if px else "false")
    cs.append("        public static float %s(this float v) { return V(%s, v); }" % (c, args))
    cs.append("        public static float %s(this int v) { return V(%s, v); }" % (c, args))
cs += ["    }", "}", ""]

# ── GDScript ──
gd = ["\t# <tokens> generated by tools/gen_tokens.py — do not edit by hand"]
for n, s, slot, kind, px in tokens:
    if px:
        expr = "metrics.dp(%d, %d, v) * metrics.density" % (s, slot)
    elif kind == 1:
        expr = "metrics.sp(%d, %d, v)" % (s, slot)
    else:
        expr = "metrics.dp(%d, %d, v)" % (s, slot)
    gd.append("func %s(v: float) -> float: return %s" % (n, expr))
gd.append("\t# </tokens>")

# ── C++ ──
STRAT = ["AD_SCALED", "AD_AUTO", "AD_PERCENT", "AD_POWER", "AD_FLUID", "AD_INTERPOLATED", "AD_LOGARITHMIC",
         "AD_DIAGONAL", "AD_PERIMETER", "AD_FIT", "AD_FILL", "AD_DENSITY"]
hpp = ["// Generated by tools/gen_tokens.py — do not edit by hand.",
       "// Family token API for C++, the AppDimens way — the token applied to a value, from the live snapshot of the",
       "// shared library (adg_publish* / adg_acquire):",
       "//   appdimens::sdp(64)  appdimens::asdp(64)  appdimens::ftsdp(120)  appdimens::sdpPh(16)",
       "//   using namespace appdimens::literals;  float hud = 64_asdp;",
       "// REFERENCE mode (games): values are px at the reference resolution → px now. Link AppDimens::games.",
       "#pragma once",
       "#include \"appdimens_games_api.h\"",
       "",
       "namespace appdimens {",
       "namespace detail {",
       "inline float token(ad_strategy s, int slot, int kind, bool px, float v) {",
       "    const ad_metrics *m = adg_acquire();",
       "    float r = v * m->table[s][slot];",
       "    if (kind == 1) r *= m->in.font_scale;",
       "    return px ? r * m->in.density : r;",
       "}",
       "} // namespace detail",
       ""]
for n, s, slot, kind, px in tokens:
    hpp.append("inline float %s(float v) { return detail::token(%s, %d, %d, %s, v); }" % (
        n, STRAT[s], slot, kind, "true" if px else "false"))
hpp += ["", "namespace literals {"]
for n, *_ in tokens:
    hpp.append("inline float operator\"\"_%s(long double v) { return %s(float(v)); }" % (n, n))
    hpp.append("inline float operator\"\"_%s(unsigned long long v) { return %s(float(v)); }" % (n, n))
hpp += ["} // namespace literals", "} // namespace appdimens", ""]

outputs = {
    os.path.join(ROOT, "dotnet", "AppDimens.Games", "Tokens.cs"): "\n".join(cs),
    os.path.join(ROOT, "native", "include", "appdimens", "tokens.hpp"): "\n".join(hpp),
}
gdp = os.path.join(ROOT, "engines", "godot", "addons", "appdimens", "appdimens.gd")
g = open(gdp).read()
a = g.index("\t# <tokens>"); b = g.index("\t# </tokens>") + len("\t# </tokens>")
outputs[gdp] = g[:a] + "\n".join(gd) + g[b:]

stale = []
for path, text in outputs.items():
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        if "--check" in sys.argv:
            stale.append(os.path.relpath(path, ROOT))
        else:
            open(path, "w").write(text)
if stale:
    sys.exit("stale generated files (run python3 tools/gen_tokens.py): " + ", ".join(stale))
print(len(tokens), "tokens")
