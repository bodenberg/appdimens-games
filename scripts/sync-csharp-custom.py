#!/usr/bin/env python3
"""Regenerates csharp/AppDimensGames/AppDimensGamesCustom.Engine.cs from the portable engine of
AppDimens.Net.Custom (appdimens-net-binding). Usage: sync-csharp-custom.py <appdimens-net-binding dir>"""
import pathlib, re, sys

src = pathlib.Path(sys.argv[1]) / "appdimens-net/src/AppDimens.Net.Custom"
files = ["CustomModel.cs", "CustomExpression.cs", "CustomEngine.cs", "CustomBuilder.cs", "CustomJson.cs"]
usings, bodies = set(), []
for name in files:
    text = (src / name).read_text()
    lines = []
    for line in text.splitlines():
        if line.startswith("using "):
            usings.add(line)
        elif line.startswith("//") and not lines or line.startswith("#nullable"):
            continue
        else:
            lines.append(line)
    body = "\n".join(lines).strip()
    body = body.replace("namespace AppDimens.Net.Custom", "namespace AppDimensGames.Custom")
    body = body.replace("<c>DimenMetrics</c>", "<c>Metrics</c>").replace("<c>Sdp</c>", "<c>MathKernels.Scaled</c>")
    bodies.append(f"// ── {name} ──\n{body}")
out = pathlib.Path(__file__).resolve().parent.parent / "csharp/AppDimensGames/AppDimensGamesCustom.Engine.cs"
out.write_text(
    "// AppDimens Games — custom scaling strategies, portable engine.\n"
    "// GENERATED by scripts/sync-csharp-custom.py from AppDimens.Net.Custom (appdimens-net-binding);\n"
    "// edit the .NET sources and re-run the script. Engine/bridge split: see AppDimensGamesCustom.cs.\n"
    "#nullable enable\n" + "\n".join(sorted(usings)) + "\n\n" + "\n\n".join(bodies) + "\n")
print(f"wrote {out}")
