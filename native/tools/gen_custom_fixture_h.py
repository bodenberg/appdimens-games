#!/usr/bin/env python3
"""tests/custom-strategy-fixture.json → tests/custom_fixture.h (C test data for appdimens_custom.h)."""
import json, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "tests", "custom-strategy-fixture.json")
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "tests", "custom_fixture.h")
f = json.load(open(src))
devs = ["phone", "tablet", "desktop", "tv", "watch", "car", "vr"]
names = list(f["screens"])
def cstr(s): return json.dumps(s)
out = ["/* Generated by tools/gen_custom_fixture_h.py — do not edit. */",
       "static const double ADC_FIX_TOL = %r;" % f["tolerance"],
       "static const char *const ADC_FIX_DOC = %s;" % cstr(json.dumps(f["document"], separators=(",", ":"))),
       "static const adc_screen ADC_FIX_SCREENS[] = {"]
for n in names:
    s = f["screens"][n]
    out.append("  {%r, %r, %r, %r, %r, %d, %d, (adc_device)%d}, /* %s */" % (
        s["width"], s["height"], s["smallestWidth"], s["density"], s["fontScale"],
        int(s["landscape"]), int(s["multiWindow"]), devs.index(s["device"]), n))
out.append("};")
out.append("typedef struct { const char *strategy; int screen; double base, factor, dp, sp_dp; const char *rules; } adc_fix_case;")
out.append("static const adc_fix_case ADC_FIX_CASES[] = {")
for c in f["cases"]:
    out.append("  {%s, %d, %r, %r, %r, %r, %s}," % (cstr(c["strategy"]), names.index(c["screen"]), c["base"],
               c["factor"], c["dp"], c["spDp"], cstr(",".join(c["rules"]))))
out.append("};")
out.append("#define ADC_FIX_COUNT %d" % len(f["cases"]))
open(dst, "w").write("\n".join(out) + "\n")
